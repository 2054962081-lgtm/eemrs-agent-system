function textList(items) {
  return items.join("；");
}

function makeCase(index, data) {
  const caseId = `EXT-${String(index).padStart(3, "0")}`;
  const mustAsk = textList(data.mustAsk);
  const forbidden = textList(data.forbidden);
  const redFlags = textList(data.redFlags);
  const expectedPoints = textList(data.expectedPoints);
  const departments = textList(data.departments);
  return {
    caseId,
    caseType: data.caseType,
    mode: data.mode ?? "quick",
    title: data.title,
    patientAge: data.age,
    patientGender: data.gender,
    specialPopulation: data.population,
    turnsText: `user: ${data.userInput}`,
    expectedDepartments: departments,
    expectedUrgency: data.urgency,
    mustAskOrMention: mustAsk,
    mustNotSay: forbidden,
    hardFailRules: textList(data.hardFailRules ?? data.forbidden),
    notes: data.notes,
    test_group: data.group,
    population_type: data.population,
    disease_category: data.category,
    user_input: data.userInput,
    expected_department: departments,
    expected_urgency: data.urgency,
    must_ask_points: mustAsk,
    red_flags: redFlags,
    forbidden_actions: forbidden,
    expected_response_points: expectedPoints,
    manual_review_level: data.reviewLevel,
    scoring_focus: data.scoringFocus,
  };
}

