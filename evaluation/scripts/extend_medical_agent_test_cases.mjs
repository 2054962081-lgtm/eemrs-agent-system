function validateCases(cases) {
  const errors = [];
  if (cases.length < 48) errors.push(`新增 case 数量不足：${cases.length}`);
  const requiredFields = [
    "user_input",
    "expected_urgency",
    "must_ask_points",
    "forbidden_actions",
  ];
  for (const item of cases) {
    for (const field of requiredFields) {
      if (!item[field]) errors.push(`${item.caseId} 缺少 ${field}`);
    }
  }
  const groups = new Set(cases.map((item) => item.test_group));
  for (const requiredGroup of ["儿童专项", "老年人专项", "孕产妇专项", "慢病用药专项", "精神心理专项"]) {
    if (!groups.has(requiredGroup)) errors.push(`缺少分组：${requiredGroup}`);
  }
  const headers = [...originalHeaders, ...extraHeaders];
  if (headers.some((header) => header.toLowerCase().includes("rag") || header.toLowerCase().includes("retrieval"))) {
    errors.push("出现 RAG 或 retrieval 相关字段");
  }
  return errors;
}

function groupCounts(cases) {
  return cases.reduce((acc, item) => {
    acc[item.test_group] = (acc[item.test_group] ?? 0) + 1;
    return acc;
  }, {});
}

